const DICTS: Record<Locale, Record<Key, string>> = { de, en, es, ru, zh };

export type MsgKey = Key;

export function translate(
  locale: Locale,
  key: MsgKey,
  vars?: Record<string, string | number>,
): string {
  const table = DICTS[locale] ?? de;
  let out = table[key] ?? de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}
